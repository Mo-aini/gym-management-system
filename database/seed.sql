INSERT INTO bookings (class_id, member_id, class_date, status)
SELECT c.id, m.id,
       CURDATE() + INTERVAL MOD(FIELD(c.day_of_week,'Mon','Tue','Wed','Thu','Fri','Sat','Sun') - WEEKDAY(CURDATE()) - 1 + 7, 7) DAY,
       'booked'
FROM classes c JOIN members m ON m.status = 'active'
WHERE MOD(c.id * 7 + m.id * 3, 5) < 3 AND m.id <> 1;

